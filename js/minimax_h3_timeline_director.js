  scheduleNodeHeightSync() {
    cancelAnimationFrame(this.layoutRAF);
    this.layoutRAF = requestAnimationFrame(() => {
      this.node.__m3tdSyncPrompt?.();
      const desiredHeight = this.requiredDirectorHeight();
      if (this.directorWidget) this.directorWidget.__m3tdHeight = DIRECTOR_HEIGHT;
      const widgetHost = this.root.closest?.(".m3td-widget-host") || this.root.parentElement;
      if (widgetHost) {
        widgetHost.classList.add("m3td-widget-host");
        const nodeH = this.node.size?.[1] || 0;
        const chromeH = Number(this.node.__m3tdChromeHeight) || 180;
        // 实际widget元素高度跟随节点，但computeSize仍返回内容高度，不会触发节点自动长高
        const finalH = Math.max(DIRECTOR_HEIGHT, nodeH > DIRECTOR_HEIGHT + chromeH + 4 ? nodeH - chromeH - 4 : DIRECTOR_HEIGHT);
        widgetHost.style.setProperty("height", `${finalH}px`, "important");
        widgetHost.style.setProperty("min-height", `${DIRECTOR_HEIGHT}px`, "important");
        widgetHost.style.setProperty("max-height", "none", "important");
        widgetHost.style.setProperty("overflow", "visible", "important");
        this.root.style.setProperty("height", `${finalH}px`, "important");
        this.root.style.setProperty("min-height", `${DIRECTOR_HEIGHT}px`, "important");
        this.root.style.setProperty("overflow", "hidden", "important");
      }
      const computed = this.node.computeSize?.();
      const currentWidth = this.node.size?.[0] || computed?.[0] || 860;
      const currentHeight = this.node.size?.[1] || 0;
      const computedHeight = Number(computed?.[1]) || 0;
      // Do not clamp the node back to its previous minimum while the user is
      // dragging a resize handle. onResize converts the vertical delta into
      // prompt height; after release, the normal layout minimum is recomputed.
      if(this.node.__m3tdIsResizing){
        this.node.setDirtyCanvas?.(true,true);
        return;
      }
      const chromeCandidate = computedHeight - desiredHeight;
      if (chromeCandidate >= 36 && chromeCandidate <= 600) {
        this.node.__m3tdChromeHeight = chromeCandidate;
      }
      const chromeHeight = Number(this.node.__m3tdChromeHeight) || 180;
      const minimumHeight = Math.ceil(DIRECTOR_HEIGHT + chromeHeight);
      // 用户手动拉高的保留，只有小于最小高度时才自动设置
      if (currentHeight < minimumHeight && Math.abs(currentHeight - minimumHeight) > 1) {
        this.node.__m3tdApplyingLayout = true;
        try { this.node.setSize?.([currentWidth, minimumHeight]); }
        finally { this.node.__m3tdApplyingLayout = false; }
      }
      this.node.__m3tdLastLayoutHeight = this.node.size?.[1];
      this.node.setDirtyCanvas?.(true, true);
    });
  }


